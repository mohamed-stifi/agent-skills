// Regenerates src/videos/index.ts from the folders in src/videos/.
// A folder is registered when it has Video.tsx + timing.json and does not start with "_".
import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve('src/videos');
const ids = fs.readdirSync(dir).filter((d) =>
  !d.startsWith('_') && fs.existsSync(path.join(dir, d, 'Video.tsx')) && fs.existsSync(path.join(dir, d, 'timing.json')));
const v = (id) => 'v_' + id.replace(/[^a-zA-Z0-9]/g, '_');
const src = `// GENERATED by scripts/registry.mjs — do not edit by hand.
${ids.map((id) => `import * as ${v(id)} from './${id}/Video';`).join('\n')}

export const videos = [
${ids.map((id) => `  {id: '${id}', component: ${v(id)}.Video, total: ${v(id)}.total},`).join('\n')}
];
`;
fs.writeFileSync(path.join(dir, 'index.ts'), src);
console.log('registered:', ids.join(', ') || '(none)');
